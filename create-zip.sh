#!/bin/bash

echo ""
echo "╔══════════════════════════════════════════════╗"
echo "║   Создание ZIP архива проекта...            ║"
echo "╚══════════════════════════════════════════════╝"
echo ""

# Удаляем старый архив если есть
if [ -f "ПУ-Регистратор.zip" ]; then
    echo "[INFO] Удаление старого архива..."
    rm "ПУ-Регистратор.zip"
fi

# Создаем временную папку для архива
if [ -d "ПУ-Регистратор_temp" ]; then
    rm -rf "ПУ-Регистратор_temp"
fi
mkdir "ПУ-Регистратор_temp"

echo "[INFO] Копирование файлов..."

# Копируем основные файлы
cp database.json "ПУ-Регистратор_temp/"
cp server.js "ПУ-Регистратор_temp/"
cp start.bat "ПУ-Регистратор_temp/"
cp start.sh "ПУ-Регистратор_temp/"
cp package.json "ПУ-Регистратор_temp/"
cp package-lock.json "ПУ-Регистратор_temp/"
cp README.md "ПУ-Регистратор_temp/"

# Копируем папки
cp -r src "ПУ-Регистратор_temp/"
cp -r dist "ПУ-Регистратор_temp/"

echo "[INFO] Создание ZIP архива..."

# Создаем ZIP архив
cd "ПУ-Регистратор_temp"
zip -r "../ПУ-Регистратор.zip" .
cd ..

# Удаляем временную папку
rm -rf "ПУ-Регистратор_temp"

echo ""
echo "╔══════════════════════════════════════════════╗"
echo "║   ✓ Архив создан успешно!                   ║"
echo "║                                              ║"
echo "║   Файл: ПУ-Регистратор.zip                  ║"
echo "╚══════════════════════════════════════════════╝"
echo ""
